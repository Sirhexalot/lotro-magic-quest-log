"""Build EN/DE/FR catalogs for Magic Quest Log from extracted client lore data.

Read-only. Writes only generated Lua catalogs and a manifest. Reads no character
memory, no plugin data and no secrets. The extractor boundary is deliberate: this
consumes a versioned lore XML export; it does not parse the binary LOTRO archives.
"""
from pathlib import Path
from collections import defaultdict, Counter
import argparse
import hashlib
import json
import re
import tempfile
import xml.etree.ElementTree as ET

SCRIPT_VERSION = 1
MARKER = '-- Generated by Magic Quest Log; do not edit.\n'
ROOT = Path(__file__).resolve().parents[1]
LOCALES = ('en', 'de', 'fr')
SECTIONS = ('story', 'missions', 'instances', 'craft', 'festivals', 'other')
HIDDEN_CATEGORIES = {'Test', 'Level Up'}
HIDDEN_AREAS = {'Eyes and Guard Tavern', 'Test', 'Unexplored Territory'}
HIDDEN_ZONES = {'Seamia', 'Unassigned'}
# World-region crosswalk. geoAreas parentId is NOT the world map hierarchy: it also
# nests Gondor and Mordor under Rhovanion, so it must never define the roots.
REGIONS = {
 'Eriador': ['Bree-land','The Shire','The Ettenmoors','Ered Luin','The Lone-lands','Angmar','The North Downs','The Misty Mountains','The Trollshaws','Evendim','Forochel','Eregion','Dunland','Enedwaith','Festival Grounds','Cardolan','Swanfleet','Hithaeglir'],
 'Rhovanion': ['Moria','Lothlórien','Mirkwood','Erebor','Strongholds of the North','The Dwarf-holds','The Vales of Anduin','Wells of Langflood','Elderslade','Gundabad','Rhovanion'],
 'Rohan': ['Great River','Rohan - Eastemnet','Rohan - Wildermore','Rohan - Westemnet','Entwash','Wold','Croftlands','Eastfold','Fangorn','Westfold','Wildermore'],
 'Gondor': ['Western Gondor','Central Gondor','Eastern Gondor','Osgiliath','Old Anórien','Far Anórien','Anórien','Anórien (After Battle)','Ithilien','The Wastes',"King's Gondor",'Anfalas','Pinnath Gelin','Belfalas & Dor-en-Ernil','Lossarnach','Lebennin','Ringló Vale'],
 'Mordor': ['Mordor','Imlad Morgul','Agarnaith','Lhingris'],
 'Tales of Yore': ['Mordor Besieged','Tales of Yore: Azanulbizar'],
}
ALIASES = {'Shire':'The Shire','Trollshaws':'The Trollshaws','Ettenmoors':'The Ettenmoors','North Downs':'The North Downs','Misty Mountains':'The Misty Mountains','Lone-lands':'The Lone-lands','Lone-Lands':'The Lone-lands','Vales of Anduin':'The Vales of Anduin','Dwarf-holds':'The Dwarf-holds','Azanulbizar':'Tales of Yore: Azanulbizar','Outer Gondor':"King's Gondor",'Bree-town':'Bree-land','Umbar Baharbêl':'Umbar','The Cape of Umbar':'Umbar','Cape of Umbar':'Umbar','The Great River':'Great River','Morgul Vale':'Imlad Morgul','Gorgoroth':'Mordor','Anórien (After)':'Anórien (After Battle)'}
STORY_CATEGORY_CODES = {'270','346','407','481'}
SHADOW_CATEGORY_CODES = {'388','389','390','391','395'}


def clean(text):
    return (text or '').replace('\\q', '"').strip()


def lua(value):
    if value is None: return 'nil'
    if isinstance(value, bool): return 'true' if value else 'false'
    if isinstance(value, (int, float)): return repr(value)
    if isinstance(value, str): return json.dumps(value, ensure_ascii=False).replace('\\/', '/')
    if isinstance(value, (list, tuple)): return '{' + ','.join(lua(v) for v in value) + '}'
    if isinstance(value, dict): return '{' + ','.join('[' + lua(str(k)) + ']=' + lua(v) for k, v in value.items()) + '}'
    raise TypeError(type(value))


class Lore:
    def __init__(self, path):
        self.path = path
        self.cache = {}
        self.enums = {}

    def parse(self, rel):
        if rel not in self.cache:
            target = self.path / rel
            if not target.is_file():
                raise ValueError('Missing source file: ' + rel)
            self.cache[rel] = ET.parse(target).getroot()
        return self.cache[rel]

    def labels(self, locale, name):
        key = ('labels', locale, name)
        if key not in self.cache:
            target = self.path / 'labels' / locale / name
            self.cache[key] = ({e.get('key'): clean(e.get('value')) for e in ET.parse(target).getroot()}
                               if target.is_file() else {})
        return self.cache[key]

    def enum(self, name, locale):
        key = ('enum', name, locale)
        if key not in self.cache:
            base = {e.get('code'): e.get('name') for e in self.parse('enums/%s.xml' % name)}
            table = self.labels(locale, 'enum-%s.xml' % name)
            self.cache[key] = {code: table.get(value, '') for code, value in base.items()}
        return self.cache[key]


def moormap_maps(path):
    """Exact texture-ID matches from MoorMap's own table. Never match by translated name."""
    found = defaultdict(list)
    if path is None:
        return found
    for match in re.finditer(r'tmpMapInfo\[(\d+)\]\s*=\s*\{([^}\n]+)', path.read_text()):
        fields = match.group(2).split(',')
        try:
            image = int(fields[2].strip(), 0)
            entry = dict(map=int(fields[0]), kind=int(fields[10]), region=int(fields[11]),
                         north=float(fields[12]), west=float(fields[13]),
                         south=float(fields[14]), east=float(fields[15]),
                         interior=int(fields[17]) if fields[17].strip().isdigit() else 0)
        except (ValueError, IndexError):
            continue
        if entry['kind'] == 1 and not entry['interior']:
            found[image].append(entry)
    return found


def build(lore_path, output, moormap_path=None, overrides=None):
    lore = Lore(lore_path)
    overrides = overrides or {}
    hidden = set(overrides.get('hidden_ids', []))
    added = overrides.get('paths', {})
    quests = list(lore.parse('quests.xml'))
    deeds = list(lore.parse('deeds.xml'))
    if len(quests) < 1000 or len(deeds) < 100:
        raise ValueError('Implausibly small source; refusing to replace a working catalog')
    geography = list(lore.parse('geoAreas.xml'))
    geo_by_id = {n.get('id'): n for n in geography}
    # Names have to be looked up by name: indexing the same table by a zone name
    # always missed, which is why every zone stayed in English.
    geo_id_by_name = {n.get('name'): n.get('id') for n in geography if n.get('name')}
    region_of = {zone: region for region, zones in REGIONS.items() for zone in zones}
    for node in geography:
        if node.tag == 'territory':
            if node.get('parentId') == '1879466303': region_of[node.get('name')] = 'Haradwaith'
            elif node.get('parentId') == '1879524677': region_of[node.get('name')] = 'Rhûn'
    area_parents = defaultdict(set)
    for node in geography:
        if node.tag == 'area' and node.get('parentId') in geo_by_id:
            area_parents[node.get('name')].add(geo_by_id[node.get('parentId')].get('name'))
    maps = {n.get('id'): n for n in lore.parse('maps/maps/maps.xml')}
    region_ids = {n.get('name'): n.get('id') for n in geography if n.tag == 'region'}
    aliases = dict(ALIASES)
    aliases.update({zone: zone for zone in region_of})
    moormap = moormap_maps(moormap_path)

    def place(category, map_node):
        if category in aliases: return aliases[category], None
        parents = area_parents.get(category, set())
        if len(parents) == 1 and next(iter(parents)) in region_of:
            return next(iter(parents)), category
        if ': ' in category:
            prefix, suffix = category.split(': ', 1)
            if prefix in aliases: return aliases[prefix], suffix
        if map_node is not None:
            name = map_node.get('name', '')
            if name in aliases: return aliases[name], None
            parents = area_parents.get(name, set())
            if len(parents) == 1 and next(iter(parents)) in region_of:
                return next(iter(parents)), name
        return None, None

    def points(achievement, map_node, steps_with_text):
        """Only positions verified against MoorMap geometry and region. Ambiguous means none."""
        if map_node is None: return []
        node = maps.get(map_node.get('mapId'))
        if node is None: return []
        candidates = moormap.get(int(node.get('imageId') or 0), [])
        if not candidates: return []
        found, seen = [], set()
        for objective in achievement.findall('objectives/objective'):
            for point in objective.iter('point'):
                try:
                    lat, lon = float(point.get('latitude')), float(point.get('longitude'))
                except (TypeError, ValueError):
                    continue
                hits = [c for c in candidates if c['south'] <= lat <= c['north'] and c['west'] <= lon <= c['east']
                        and str(c['region']) == map_node.get('region')]
                if len(hits) != 1: continue
                # A position is only tied to a step that is actually shown.
                if objective.get('index') not in steps_with_text: continue
                key = (hits[0]['map'], round(lat, 5), round(lon, 5), objective.get('index'))
                if key in seen: continue
                seen.add(key)
                found.append(dict(map=hits[0]['map'], lat=round(lat, 5), lon=round(lon, 5),
                                  step=objective.get('index', '')))
        return found

    manifest = {'schema': SCRIPT_VERSION, 'sources': {}, 'locales': {}, 'coverage': {}}
    for rel in ('quests.xml', 'deeds.xml', 'geoAreas.xml', 'maps/maps/maps.xml'):
        manifest['sources'][rel] = hashlib.sha256((lore_path / rel).read_bytes()).hexdigest()
    if moormap_path is not None:
        manifest['sources']['MoorMap/Defaults.lua'] = hashlib.sha256(moormap_path.read_bytes()).hexdigest()
    output.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix='.mql-build-', dir=str(output.parent)))
    try:
        for locale in LOCALES:
            geo_labels = lore.labels(locale, 'geoAreas.xml')
            english_geo = lore.labels('en', 'geoAreas.xml')
            categories = {kind: lore.enum(name, locale) for kind, name in
                          (('quests', 'QuestCategory'), ('deeds', 'DeedCategory'))}
            english_categories = {kind: lore.enum(name, 'en') for kind, name in
                                  (('quests', 'QuestCategory'), ('deeds', 'DeedCategory'))}
            stats, fallback, unmatched_zones = Counter(), Counter(), Counter()

            def translate(name):
                if not name: return name
                ident = geo_id_by_name.get(name) or region_ids.get(name)
                return geo_labels.get(ident) or english_geo.get(ident) or name

            for kind, source in (('quests', quests), ('deeds', deeds)):
                table = lore.labels(locale, kind + '.xml')
                english = lore.labels('en', kind + '.xml')
                npc = lore.labels(locale, 'npc.xml')

                def text(key):
                    if not key: return ''
                    value = table.get(key)
                    if value: return value
                    value = english.get(key)
                    if value: fallback[kind] += 1
                    return value or ''

                records, seen = [], set()
                for achievement in source:
                    ident = '%08X' % int(achievement.get('id'))
                    if ident in seen: raise ValueError('Duplicate id ' + ident)
                    seen.add(ident)
                    category = english_categories[kind].get(achievement.get('category'), '')
                    category_label = categories[kind].get(achievement.get('category')) or category
                    map_node = achievement.find('map')
                    zone, area = place(category, maps.get(map_node.get('mapId')) if map_node is not None else None)
                    if ident in hidden or category in HIDDEN_CATEGORIES or area in HIDDEN_AREAS or zone in HIDDEN_ZONES:
                        stats[kind + '_hidden'] += 1
                        continue
                    path = []
                    code = achievement.get('category', '')
                    volume = re.match(r'Epic - Vol\. ([IVX]+)', category) if kind == 'quests' else None
                    if volume or code in STORY_CATEGORY_CODES or code in SHADOW_CATEGORY_CODES:
                        path.append({'k': 'section:story', 'n': '@story'})
                        if volume:
                            path.append({'k': 'volume:' + volume.group(1), 'n': '@volume:' + volume.group(1)})
                        elif code in SHADOW_CATEGORY_CODES:
                            path.append({'k': 'story:shadow', 'n': '@shadow'})
                        if category_label and category_label != path[-1]['n']:
                            path.append({'k': 'category:' + code, 'n': category_label})
                    elif zone and zone in region_of:
                        region = region_of[zone]
                        path.append({'k': 'region:' + region, 'n': translate(region)})
                        path.append({'k': 'zone:' + zone, 'n': translate(zone)})
                        # Tree shape is decided on the English base labels, so every
                        # language has the identical structure and only names differ.
                        english_area = None
                        if area:
                            english_area = english_geo.get(geo_id_by_name.get(area)) or area
                            label = translate(area)
                            if label == area and ': ' in category_label:
                                label = category_label.split(': ', 1)[1]
                            path.append({'k': 'area:' + zone + ':' + area, 'n': label})
                        if category and category != zone and category != english_area:
                            path.append({'k': 'category:' + code, 'n': category_label})
                    else:
                        if zone and zone not in region_of:
                            unmatched_zones[zone] += 1
                        section = 'other'
                        if category.startswith('Mission'): section = 'missions'
                        elif (category == 'Skirmish' or category.startswith(('Epic Battles', 'Dungeons'))
                              or 'Instances' in category): section = 'instances'
                        elif category.startswith('Craft'): section = 'craft'
                        elif ('Festival' in category or 'Anniversary' in category
                              or category in ('Farmers Faire', 'Hobnanigans')
                              or category.startswith('Midsummer')): section = 'festivals'
                        path.append({'k': 'section:' + section, 'n': '@' + section})
                        path.append({'k': 'category:' + code, 'n': category_label or '@other'})
                    if ident in added:
                        path = added[ident]
                    steps = []
                    for objective in achievement.findall('objectives/objective'):
                        narrative, goals = [], []
                        for dialog in objective.findall('dialog'):
                            line = text(dialog.get('text'))
                            if line and line not in narrative: narrative.append(line)
                        line = text(objective.get('text'))
                        if line and line not in narrative: narrative.append(line)
                        for event in objective.iter():
                            line = text(event.get('progressOverride'))
                            if line:
                                goal = {'t': line}
                                if (event.get('count') or '').isdigit(): goal['c'] = int(event.get('count'))
                                if goal not in goals: goals.append(goal)
                        if narrative or goals:
                            steps.append({'i': objective.get('index', ''), 'n': narrative, 'g': goals})
                    targets = points(achievement, map_node, set(step['i'] for step in steps))
                    for target in targets:
                        # Name the place only from game data; never invented.
                        for objective in achievement.findall('objectives/objective'):
                            if objective.get('index') != target['step']: continue
                            for event in objective.iter():
                                reference = event.get('npcId') or event.get('did')
                                if reference and reference in npc:
                                    target['n'] = npc[reference]
                                    break
                            if 'n' in target: break
                    records.append({'id': ident, 'name': text(str(int(achievement.get('id')))) or achievement.get('name') or ident,
                                    'd': text(achievement.get('description')), 'l': achievement.get('level', ''),
                                    'p': path, 's': steps, 't': targets})
                    stats[kind] += 1
                    stats[kind + '_with_targets'] += 1 if targets else 0
                    stats[kind + '_targets'] += len(targets)
                (staging / ('%s_%s.lua' % (kind.capitalize(), locale))).write_text(
                    MARKER + 'MagicQuestLog = MagicQuestLog or {};\nMagicQuestLog.Data = MagicQuestLog.Data or {};\n'
                    'MagicQuestLog.Data.%s_%s = {\n' % (kind, locale)
                    + ',\n'.join(lua(r) for r in records) + '\n};\n', encoding='utf-8')
            manifest['locales'][locale] = {'counts': dict(stats), 'english_fallback_texts': dict(fallback),
                                           'zones_without_region': dict(unmatched_zones)}
        (staging / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
        for source in sorted(staging.rglob('*')):
            if not source.is_file(): continue
            target = output / source.relative_to(staging)
            if source.suffix == '.lua' and target.is_file() and not target.read_text(encoding='utf-8').startswith(MARKER):
                raise ValueError('Refusing to replace a file Magic Quest Log did not generate: ' + str(target))
            target.parent.mkdir(parents=True, exist_ok=True)
            temp = target.with_name(target.name + '.new')
            temp.write_bytes(source.read_bytes())
            temp.replace(target)
    finally:
        import shutil
        shutil.rmtree(staging, ignore_errors=True)
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Build Magic Quest Log catalogs (read-only).')
    parser.add_argument('--lore', type=Path, required=True, help='Extracted lore XML directory')
    parser.add_argument('--moormap', type=Path, default=None, help='MoorMap Defaults.lua for position checks')
    parser.add_argument('--output', type=Path, default=ROOT / 'plugin/MagicQuestLog/Data')
    parser.add_argument('--overrides', type=Path, default=ROOT / 'tools/overrides.json')
    options = parser.parse_args()
    data = json.loads(options.overrides.read_text(encoding='utf-8')) if options.overrides.is_file() else {}
    report = build(options.lore, options.output, options.moormap, data)
    print(json.dumps({k: v['counts'] for k, v in report['locales'].items()}, ensure_ascii=False, indent=2))
