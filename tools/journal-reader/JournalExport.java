import java.io.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.time.LocalDate;
import java.util.*;
import delta.games.lotro.dat.data.*;
import delta.games.lotro.dat.wlib.ClassInstance;
import delta.games.lotro.memory.*;
import delta.games.lotro.memory.io.jna.*;
import delta.games.lotro.memory.wsl.WslInspector;
import delta.games.lotro.memory.extraction.SummaryExtractor;

/**
 * Read the quest journal of the running LOTRO client and write MagicQuestLog's
 * Progress.lua directly.
 *
 * Read-only towards the game: no write function for the client process is called,
 * no general memory dump is taken, and no account or session data is exported.
 * What is read: the character summary (only to name the file) and the two journal
 * tables m_completedQuestRecords / m_currentQuestRecords.
 *
 * Usage: JournalExport <client-directory> <output-lua> [character|-]
 *
 * Exit codes: 0 written, 1 argument/environment problem, 2 game or character not usable,
 * 3 no plausible records (nothing written).
 */
public final class JournalExport {
  private static final String HEADER = "-- Generated by Magic Quest Log; do not edit.";

  private static void stage(String text) { System.out.println(text); System.out.flush(); }

  private static void fail(int code, String message) {
    System.err.println("ERROR: " + message);
    System.exit(code);
  }

  public static void main(String[] args) {
    if (args.length < 2 || args.length > 3) {
      fail(1, "usage: JournalExport <client-directory> <output-lua> [character|-]");
    }
    String clientDirectory = args[0];
    Path output = Paths.get(args[1]);
    String wanted = args.length == 3 ? args[2] : "-";
    if (!Files.isDirectory(Paths.get(clientDirectory))) {
      fail(1, "client directory not found: " + clientDirectory);
    }
    // Never replace a file this tool did not write.
    if (Files.isRegularFile(output)) {
      String first;
      try (BufferedReader reader = Files.newBufferedReader(output, StandardCharsets.UTF_8)) {
        first = reader.readLine();
      } catch (IOException error) {
        fail(1, "cannot read " + output + ": " + error.getMessage());
        return;
      }
      if (first == null || !first.startsWith(HEADER)) {
        fail(1, "refusing to replace " + output + ": it was not written by this tool");
      }
    }

    DatConfiguration configuration = new DatConfiguration();
    configuration.setRootPath(new File(clientDirectory));
    configuration.setLocale("de");
    stage("Opening client data files...");
    DataFacade data = new DataFacade(configuration);
    WinInterface access = new WinInterface();
    try {
      if (!data.getErrors().isEmpty()) {
        fail(2, "client data files could not be opened: " + data.getErrors());
      }
      List<LotroProcess> processes = access.findAllLotroProcesses();
      stage("LOTRO processes found: " + processes.size());
      if (processes.size() != 1) {
        fail(2, "exactly one LOTRO client must be running (found " + processes.size() + "). "
            + "Start the game and log the character in, then run again.");
      }
      LotroProcess process = processes.get(0);
      stage("Checking the active character...");
      if (!new SummaryExtractor().doIt(process, data) || process.getSummary() == null) {
        fail(2, "character summary unavailable; enter the world first");
      }
      String name = process.getSummary().getName();
      if (wanted != null && !"-".equals(wanted) && !wanted.equalsIgnoreCase(name)) {
        fail(2, "the active character is " + name + ", not " + wanted);
      }
      stage("Character: " + name);
      if (!access.start(process)) {
        fail(2, "cannot open the LOTRO process for reading; try running as administrator");
      }
      MemoryDataFacade memory = new MemoryDataFacade(access, data);
      stage("Locating local player and quest journal...");
      ClassInstance player = new WslInspector(memory.getReferenceTableController()).findLocalPlayer();
      if (player == null) {
        fail(2, "local player unavailable; enter the world first");
      }
      Object journalObject = player.getAttributeValue("m_cCQuestJournal");
      if (!(journalObject instanceof ClassInstance)) {
        fail(2, "quest journal unavailable");
      }
      ClassInstance journal = (ClassInstance) journalObject;
      Object done = journal.getAttributeValue("m_completedQuestRecords");
      Object active = journal.getAttributeValue("m_currentQuestRecords");
      if (!(done instanceof Map) || !(active instanceof Map)) {
        fail(2, "quest record maps unavailable");
      }
      Map<?, ?> completed = (Map<?, ?>) done;
      Map<?, ?> current = (Map<?, ?>) active;
      // An empty result is a failed read, not a character without progress.
      if (completed.isEmpty()) {
        fail(3, "completed records are empty; refusing to claim success");
      }
      if (completed.size() > 200000 || current.size() > 20000) {
        fail(3, "implausible record count (" + completed.size() + "/" + current.size() + ")");
      }
      List<Long> completedIds = ids(completed);
      List<Long> currentIds = ids(current);
      String text = lua(name, completedIds, currentIds);
      Path parent = output.toAbsolutePath().getParent();
      if (parent != null) Files.createDirectories(parent);
      Path temporary = output.resolveSibling(output.getFileName() + ".new");
      Files.write(temporary, text.getBytes(StandardCharsets.UTF_8));
      Files.move(temporary, output, StandardCopyOption.REPLACE_EXISTING);
      stage("Wrote " + output);
      stage("  completed: " + completedIds.size() + ", active: " + currentIds.size());
      stage("  Reload the plugin in game: /plugins unload MagicQuestLog, /plugins load MagicQuestLog");
    } catch (Exception error) {
      fail(2, error.getClass().getSimpleName() + ": " + error.getMessage());
    } finally {
      access.dispose();
      data.dispose();
    }
  }

  /** Record keys are quest or deed ids; the values are not needed. */
  private static List<Long> ids(Map<?, ?> source) {
    List<Long> result = new ArrayList<Long>();
    for (Object key : source.keySet()) {
      if (!(key instanceof Number)) {
        throw new IllegalStateException("unexpected record id type: "
            + (key == null ? "null" : key.getClass().getName()));
      }
      result.add(((Number) key).longValue() & 0xffffffffL);
    }
    Collections.sort(result);
    return result;
  }

  private static String luaString(String value) {
    return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
  }

  /**
   * Our Progress.lua format. Finished ids go into "completed", which is all the
   * plugin displays; active ones are kept separately so nothing is lost. The
   * journal does not say whether an id is a quest or a deed — the catalog decides
   * that, which is why no classification happens here.
   */
  private static String lua(String character, List<Long> completed, List<Long> current) {
    StringBuilder text = new StringBuilder();
    text.append(HEADER).append('\n');
    text.append("MagicQuestLog = MagicQuestLog or {};\n");
    text.append("MagicQuestLog.Data = MagicQuestLog.Data or {};\n");
    text.append("MagicQuestLog.Data.progress = {\n");
    text.append("\t[\"__version\"] = \"1\",\n");
    text.append("\t[\"character\"] = ").append(luaString(character)).append(",\n");
    text.append("\t[\"date\"] = ").append(luaString(LocalDate.now().toString())).append(",\n");
    text.append("\t[\"source\"] = ").append(luaString("quest journal read from the running client")).append(",\n");
    text.append("\t[\"completed\"] = {\n");
    for (Long id : completed) {
      text.append(String.format(Locale.ROOT, "\t\t[\"%08X\"] = true,\n", id));
    }
    text.append("\t},\n");
    text.append("\t[\"current\"] = {\n");
    for (Long id : current) {
      text.append(String.format(Locale.ROOT, "\t\t[\"%08X\"] = true,\n", id));
    }
    text.append("\t},\n");
    text.append("\t[\"repeated\"] = {},\n");
    text.append("\t[\"unknown\"] = {},\n");
    text.append("};\n");
    return text.toString();
  }
}
