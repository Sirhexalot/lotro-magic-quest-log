"""Verify a progress file written by the journal reader. No game data needed.

Checks that the generated Lua is loadable, has our header and the shape the
plugin expects, and that every id looks like a game id.
"""
from pathlib import Path
import re
import sys
from lupa.lua51 import LuaRuntime

HEADER = '-- Generated by Magic Quest Log; do not edit.'
HEX = re.compile(r'^[0-9A-F]{8}$')


def verify(path):
    text = path.read_text(encoding='utf-8')
    assert text.startswith(HEADER), 'missing generator header'
    runtime = LuaRuntime()
    runtime.execute(text)
    data = runtime.globals().MagicQuestLog.Data.progress
    assert data is not None, 'no progress table'
    character = data['character']
    assert character and str(character).strip(), 'no character name'
    completed = set(data['completed'] or {})
    current = set(data['current'] or {})
    assert completed, 'no completed ids'
    for ident in list(completed) + list(current):
        assert HEX.match(ident), 'bad id %r' % ident
    overlap = completed & current
    for ident in completed:
        assert data['completed'][ident] is True, 'completed must be true, not %r' % data['completed'][ident]
    return {'character': str(character), 'completed': len(completed),
            'current': len(current), 'in_both': len(overlap),
            'states': len(set(data['states'] or {})) if data['states'] is not None else 0}


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('usage: verify_progress.py <Progress.lua>')
    result = verify(Path(sys.argv[1]))
    print('OK  %(character)s: %(completed)d completed, %(current)d active, %(in_both)d in both' % result)
