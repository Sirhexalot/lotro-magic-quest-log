"""Build the plugin's Progress.lua from LOTRO Companion's character files.

Companion writes, per imported character, plain XML next to its own data:

    ~/.lotrocompanion/data/characters/<account>/<server>/<character>/
        questsStatus.xml   <questStatus key="70000006" state="COMPLETED"/>
        deedsStatus.xml    <deedStatus  key="70000CFF" state="COMPLETED"/>

Those two files are all this script needs, so no memory access, no game process
and no third-party code is involved. The LOTRO Compendium import works the same
way, which is why the format is known to be stable.

Usage:
    python3 build_progress_from_companion.py                 # list characters
    python3 build_progress_from_companion.py <character>     # write Progress.lua
    python3 build_progress_from_companion.py --dir <data> <character>

Where <data> is Companion's data directory, by default
~/.lotrocompanion/data. The output is written to
plugin/MagicQuestLog/Data/Progress.lua and only after all input was read.
"""
from pathlib import Path
import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
TARGET = ROOT / 'plugin/MagicQuestLog/Data/Progress.lua'
HEADER = '-- Generated by Magic Quest Log; do not edit.'
DEFAULT_DATA = Path.home() / '.lotrocompanion' / 'data'
FILES = (('questsStatus.xml', 'questStatus'), ('deedsStatus.xml', 'deedStatus'))
HEX = re.compile(r'^[0-9A-Fa-f]{8}$')
COMPLETED = 'COMPLETED'


def lua_string(value):
    return '"' + str(value).replace('\\', '\\\\').replace('"', '\\"') + '"'


def find_characters(data):
    """Every character directory that holds at least one status file."""
    found = []
    characters = data / 'characters'
    if not characters.is_dir():
        return found
    for quests in sorted(characters.rglob('questsStatus.xml')):
        directory = quests.parent
        found.append({'name': directory.name, 'server': directory.parent.name,
                      'account': directory.parent.parent.name, 'directory': directory})
    return found


def read_status(path, element):
    """Ids and their state. The id is the key; the state says what it means."""
    if not path.is_file():
        return None
    root = ET.parse(path).getroot()
    rows = {}
    for node in root.iter(element):
        key = node.get('key')
        if not key or not HEX.match(key):
            raise ValueError('%s: unexpected id %r' % (path.name, key))
        state = (node.get('state') or '').strip().upper()
        if not state:
            raise ValueError('%s: %s has no state; the file looks outdated'
                             % (path.name, key))
        rows[key.upper()] = state
    return rows


def collect(character):
    completed, states = set(), {}
    for name, element in FILES:
        rows = read_status(character['directory'] / name, element)
        if rows is None:
            continue
        for key, state in rows.items():
            states[key] = state
            if state == COMPLETED:
                completed.add(key)
    return completed, states


def render(character, completed, states):
    counts = {}
    for state in states.values():
        counts[state] = counts.get(state, 0) + 1
    lines = [HEADER]
    lines.append('MagicQuestLog = MagicQuestLog or {};')
    lines.append('MagicQuestLog.Data = MagicQuestLog.Data or {};')
    lines.append('MagicQuestLog.Data.progress = {')
    lines.append('\t["__version"] = "1",')
    lines.append('\t["character"] = %s,' % lua_string(character['name']))
    lines.append('\t["date"] = %s,' % lua_string(states.get('__date', '')))
    lines.append('\t["source"] = %s,' % lua_string(
        'LOTRO Companion questsStatus.xml / deedsStatus.xml'))
    # Only completion is used for display; the other states are kept so nothing
    # that the client reported gets lost.
    lines.append('\t["completed"] = {')
    for ident in sorted(completed):
        lines.append('\t\t["%s"] = true,' % ident)
    lines.append('\t},')
    lines.append('\t["current"] = {},')
    lines.append('\t["repeated"] = {},')
    lines.append('\t["unknown"] = {},')
    lines.append('\t["states"] = {')
    for ident in sorted(states):
        lines.append('\t\t["%s"] = %s,' % (ident, lua_string(states[ident])))
    lines.append('\t},')
    lines.append('};')
    return '\n'.join(lines) + '\n', counts


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('character', nargs='?', help='character name to export')
    parser.add_argument('--dir', type=Path, default=DEFAULT_DATA,
                        help="Companion's data directory (default %s)" % DEFAULT_DATA)
    options = parser.parse_args()

    characters = find_characters(options.dir)
    if not characters:
        print('No character files under %s' % (options.dir / 'characters'))
        print('Import a character in LOTRO Companion first; this script reads what')
        print('Companion wrote, it cannot read the game itself.')
        return 1
    if options.character is None:
        print('Characters found:')
        for character in characters:
            print('  %-24s %s / %s' % (character['name'], character['server'], character['account']))
        print()
        print('Run again with a name to write Progress.lua.')
        return 0

    wanted = [c for c in characters if c['name'].lower() == options.character.lower()]
    if not wanted:
        print('No character called %r. Found: %s'
              % (options.character, ', '.join(c['name'] for c in characters)))
        return 1
    if len(wanted) > 1:
        print('That name exists on several accounts or servers; use --dir to point at one.')
        return 1

    character = wanted[0]
    completed, states = collect(character)
    if not completed:
        print('%s has no completed entries; refusing to write an empty progress file.'
              % character['name'])
        return 1
    if TARGET.is_file() and not TARGET.read_text(encoding='utf-8').startswith(HEADER):
        print('Refusing to replace %s: it was not generated by this tool.' % TARGET)
        return 1
    text, counts = render(character, completed, states)
    TARGET.write_text(text, encoding='utf-8')
    print('Wrote %s' % TARGET)
    print('  character %s: %d completed of %d entries'
          % (character['name'], len(completed), len(states)))
    for state in sorted(counts):
        print('    %-12s %d' % (state, counts[state]))
    print()
    print('Reload the plugin in game: /plugins unload MagicQuestLog, /plugins load MagicQuestLog')
    return 0


if __name__ == '__main__':
    sys.exit(main())
