"""Turn a verified character export into the plugin's progress data file.

Source: a journal export (see Companion-Test/exporter in that workspace) as JSON
with one list of quests and one of deeds. Only ids and status are used; the
catalogs stay untouched, and the plugin reads this file in addition to them.

Unknown ids stay listed separately: they belong to no known quest or deed, and
guessing their kind would be wrong. They are kept so a later catalog can resolve
them, and the plugin simply never matches them.

Run:  python3 MagicQuestLog/tools/build_progress.py <export.json>
"""
from pathlib import Path
import argparse
import json
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
TARGET = ROOT / 'plugin/MagicQuestLog/Data/Progress.lua'
HEADER = '-- Generated by Magic Quest Log; do not edit.'
HEX = set('0123456789ABCDEF')


def lua_string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def checked_id(value):
    text = str(value).upper()
    assert len(text) == 8 and set(text) <= HEX, 'bad id %r' % value
    return text


def collect(export):
    completed, current, unknown = set(), set(), set()
    for quest in export.get('quests', []):
        target = completed if quest.get('status') == 'COMPLETED' else current
        target.add(checked_id(quest['id_hex']))
    for deed in export.get('deeds', []):
        target = completed if deed.get('journal_status') == 'COMPLETED' else current
        target.add(checked_id(deed['id_hex']))
    for record in export.get('unknown_records', []):
        unknown.add(checked_id(record['id_hex']))
    # Repeatable lines can be finished and running at the same time. Finished
    # wins for counting; the overlap stays visible instead of being hidden.
    repeated = completed & current
    current = current - repeated
    assert not (unknown & (completed | current)), 'unknown id must stay separate'
    return completed, current, unknown, repeated


def render(export, completed, current, unknown, repeated):
    lines = [HEADER]
    lines.append("MagicQuestLog = MagicQuestLog or {};")
    lines.append("MagicQuestLog.Data = MagicQuestLog.Data or {};")
    lines.append("MagicQuestLog.Data.progress = {")
    lines.append('\t["__version"] = "1",')
    lines.append('\t["character"] = %s,' % lua_string(str(export.get('character', ''))))
    lines.append('\t["date"] = %s,' % lua_string(str(export.get('date', ''))))
    lines.append('\t["source"] = %s,' % lua_string(str(export.get('source', ''))))
    for name, ids in (('completed', completed), ('current', current),
                      ('repeated', repeated), ('unknown', unknown)):
        lines.append('\t["%s"] = {' % name)
        for ident in sorted(ids):
            lines.append('\t\t["%s"] = true,' % ident)
        lines.append('\t},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('export', type=Path, help='JSON export of one character')
    source = parser.parse_args().export
    assert source.is_file(), 'missing export: %s' % source
    if TARGET.is_file():
        existing = TARGET.read_text(encoding='utf-8').splitlines()
        assert existing and existing[0] == HEADER, 'refusing to overwrite %s' % TARGET
    export = json.loads(source.read_text(encoding='utf-8'))
    completed, current, unknown, repeated = collect(export)
    TARGET.write_text(render(export, completed, current, unknown, repeated), encoding='utf-8')
    print('Wrote %s' % TARGET)
    print('  character %s: %d finished, %d active, %d both, %d unknown ids'
          % (export.get('character'), len(completed), len(current), len(repeated), len(unknown)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
