"""Build the EN/DE/FR plugin catalogs from our own DAT export.

Input is the export produced by `Companion-Test/source-exporter` (quests.json,
deeds.json, areas.json, locations.json, manifest.json), the category enum dump
(`enums/enum-names.json`) and MoorMap's map table. No LOTRO Companion XML is read
and no Companion application is involved.

Read-only for every input. Writes only into the plugin's Data directory, and only
over files carrying the generator marker.

Run:
    python3 MagicQuestLog/tools/build_catalog_from_export.py \
        --export <export-dir> --enums <enum-names.json> --moormap <Defaults.lua>
"""
