SENTENCE = re.compile(r'([a-zäöüßàâçéèêëîïôûùœ]{2})\.([A-ZÄÖÜÀÂÇÉÈÊ][a-zäöüßàâçéèêëîïôûùœ])')
CHOICE = re.compile(r'\$\{[A-Z_]+:([^}]*)\}')


def choice(match):
    """${PLAYERNAME:Entdecker[m]|Entdeckerin[f]} -> "Entdecker / Entdeckerin":
    the game picks by the character's gender, the catalogue shows both,
    masculine first."""
    forms = []
    for part in match.group(1).split('|'):
        word = re.sub(r'\[[^\]]*\]', '', part).strip()
        tag = re.search(r'\[([a-z]+)\]', part)
        if word and word not in [w for _, w in forms]:
            forms.append((0 if tag and tag.group(1) == 'm' else 1, word))
    forms.sort(key=lambda pair: pair[0])
    return ' / '.join(word for _, word in forms)


def clean(text):
    """Game text: literal \\q is a quote, literal \\n is a line break, gender
    choices become "masculine / feminine"."""
    if text is None:
        return ''
    text = CHOICE.sub(choice, text)
    text = text.replace('\\q', '"').replace('\\n', '\n')
    # Small slips in the game text, fixed for reading, words unchanged: a sentence
    # running into the next ("Morgul.Ihr") and a stray dash after a colon
    # ("Tal der Hexerei:- Die Prüfung").
    text = SENTENCE.sub(r'\1. \2', text)
    text = text.replace(':- ', ': ').replace(':-', ': ')
    return text.strip()


REWARD_TAG = re.compile(r'\[[A-Za-z]{1,4}\]')


def reward_text(text):
    """Item or virtue name: strip quality/plural tags and stray whitespace.

    Names carry markers such as [e] (equipment), [n], [p]; some virtue labels
    arrive with an encoded line break. None of it belongs on screen. A gendered
    name keeps its first form, so it stays a name and not a phrase.
    """
    text = html.unescape(text or '')
    text = re.sub(r'\$\{[A-Z_]+:([^}]*)\}',
                  lambda m: REWARD_TAG.sub('', m.group(1).split('|')[0]).strip(), text)
    text = REWARD_TAG.sub('', text)
    text = re.sub(r'\s+', ' ', text)
    return text.strip()


def title_choice(match):
    """A title's placeholder. Two forms read as "Hero / Heroine"; a class list
    with ten forms would only clutter, so the first is taken."""
    forms = []
    for part in match.group(1).split('|'):
        word = REWARD_TAG.sub('', part).strip()
        if word and word not in forms:
            forms.append(word)
    return ' / '.join(forms[:2]) if len(forms) <= 2 else forms[0]


def title_text(text):
    """The title itself, without the character's name that precedes it.

    The DAT renderer turns ${RANK}${NAME}${SURNAME} into the literal words
    "RANK NAME SURNAME"; 66 records keep the raw placeholders.
    """
    text = html.unescape(text or '').strip()
    rank = re.match(r'^RANK\s+(.+?)\s+NAME\s+SURNAME', text)
    if rank:
        # A rank standing before the name ("RANK Wild NAME SURNAME").
        return reward_text(rank.group(1))
    text = re.sub(r'^(?:RANK\s+)?NAME\s+SURNAME', '', text)
    for token in ('${RANK}${RANK: [E]}', '${NAME}${SURNAME: [E]}${SURNAME}',
                  '${RANK}', '${NAME}', '${SURNAME: [E]}', '${SURNAME}'):
        text = text.replace(token, '')
    text = re.sub(r'\$\{[A-Z_]+:([^}]*)\}', title_choice, text)
    text = reward_text(text)
    return text.lstrip(',').strip()


def reward_entries(props, rewards, locale):
    """Rewards a record's table grants, in the compact form the plugin reads.

    [i] fixed item, [c] one of several, [t] title, [v] virtue, [tr] trait, [e] emote.
    Item entries: name, quality, level, count (fixed only), bound.
    """
    if not rewards:
        return []
    table = (rewards.get('tables') or {}).get('%08X' % (props.get('Quest_QuestTreasureDID') or 0))
    if not table:
        return []
    entries, items = [], rewards.get('items') or {}

    def item(ident, count, kind):
        record = items.get(ident)
        if not record:
            return None
        name = reward_text(record.get('n', {}).get(locale, record.get('n', {}).get('en')))
        if not name:
            return None
        entry = [kind, name]
        for key in ('q', 'l'):
            entry.append(record[key] if record.get(key) is not None else 0)
        if kind == 'i':
            entry.append(count)
        entry.append(record.get('b', 0))
        return entry

    for ident, count in table.get('fixed', []):
        entry = item(ident, count, 'i')
        if entry:
            entries.append(entry)
    for ident, _ in table.get('choice', []):
        entry = item(ident, 1, 'c')
        if entry:
            entries.append(entry)
    virtues = rewards.get('virtues') or {}
    for ident, _ in table.get('virtues', []):
        record = virtues.get(str(ident))
        name = reward_text((record or {}).get('n', {}).get(locale, (record or {}).get('n', {}).get('en')))
        if name:
            entries.append(['v', name])
    for key, kind in (('titles', 't'), ('traits', 'tr'), ('emotes', 'e')):
        pool = rewards.get(key) or {}
        for ident in table.get(key, []):
            if not isinstance(ident, str):
                continue
            record = pool.get(ident)
            name = (record or {}).get('n', {}).get(locale, (record or {}).get('n', {}).get('en'))
            name = title_text(name) if kind == 't' else reward_text(name)
            if name:
                entries.append([kind, name])
    return entries


def fold(text):
    """Accent-free lowercase form for name comparisons between languages."""
    text = (text or '').lower()
    for source, target in (('á','a'),('à','a'),('â','a'),('ä','a'),('ã','a'),('å','a'),
                           ('é','e'),('è','e'),('ê','e'),('ë','e'),
                           ('í','i'),('ì','i'),('î','i'),('ï','i'),
                           ('ó','o'),('ò','o'),('ô','o'),('ö','o'),('õ','o'),
                           ('ú','u'),('ù','u'),('û','u'),('ü','u'),
                           ('ç','c'),('ñ','n'),('ß','ss')):
        text = text.replace(source, target)
    return text


def lua(value):
    if value is None:
        return 'nil'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False).replace('\\/', '/')
    if isinstance(value, (list, tuple)):
        return '{' + ','.join(lua(v) for v in value) + '}'
    if isinstance(value, dict):
        return '{' + ','.join('[' + lua(str(k)) + ']=' + lua(v) for k, v in value.items()) + '}'
    raise TypeError(type(value))


def counters(text):
    """The DAT renderer strips the ${...} wrapper, so counting marks arrive as
    "NUMBER/TOTAL". Restore what the plugin's text resolver understands."""
    if 'NUMBER' not in text and 'TOTAL' not in text:
        return text
    return re.sub(r'\(\s*NUMBER\s*/\s*TOTAL\s*([^)]*)\)',
                  lambda m: '(${NUMBER}/${TOTAL}' + m.group(1) + ')', text)


def walk_events(container, visit):
    stack = [container]
    while stack:
        current = stack.pop()
        if isinstance(current, list):
            stack.extend(current)
        elif isinstance(current, dict):
            visit(current)
            for value in current.values():
                if isinstance(value, (list, dict)):
                    stack.append(value)


class Source:
    def __init__(self, directory):
        self.directory = directory
        self.manifest = json.loads((directory / 'manifest.json').read_text(encoding='utf-8'))
        self.quests = json.loads((directory / 'quests.json').read_text(encoding='utf-8'))
        self.deeds = json.loads((directory / 'deeds.json').read_text(encoding='utf-8'))
        self.areas = json.loads((directory / 'areas.json').read_text(encoding='utf-8'))
        self.area_by_id = {r['id']: r for r in self.areas}
        self.locations = json.loads((directory / 'locations.json').read_text(encoding='utf-8'))

    def load_landblocks(self, path):
        """Landblock -> area id, so a target position can be tied to a territory.

        Only used as a fallback for entries whose category is not a zone. The table
        is a plain index; nothing about a quest is invented from it.
        """
        if path is None:
            return {}
        import xml.etree.ElementTree as ET
        index = {}
        for block in ET.parse(path).getroot():
            index[(block.get('region'), block.get('blockX'), block.get('blockY'))] = block.get('areaId')
        return index

    def territory_name(self, area_id):
        record = self.area_by_id.get('%08X' % (int(area_id) & 0xffffffff))
        if record is None:
            return None
        props = record.get('properties') or {}
        parent = props.get('Area_Territory')
        if parent is not None:
            record = self.area_by_id.get('%08X' % (parent & 0xffffffff))
            if record is None:
                return None
            props = record.get('properties') or {}
        return (props.get('Area_Name') or {}).get('texts', {}).get('en')

    def area_of_territory(self):
        """Sub-area name -> set of territory names it belongs to.

        Keyed by the area's own name, because a quest category carries a name, not an
        id. A name that occurs under more than one territory stays ambiguous and is
        never guessed into a zone.
        """
        territory_by_id = {}
        for record in self.areas:
            props = record.get('properties') or {}
            name = (props.get('Area_Name') or {}).get('texts', {}).get('en')
            if name and props.get('Area_Territory') is None:
                territory_by_id['%08X' % (int(record['id'], 16))] = name
        parents = defaultdict(set)
        for record in self.areas:
            props = record.get('properties') or {}
            parent = props.get('Area_Territory')
            if parent is None:
                continue
            name = (props.get('Area_Name') or {}).get('texts', {}).get('en')
            territory = territory_by_id.get('%08X' % (parent & 0xffffffff))
            if name and territory:
                parents[name].add(territory)
        return parents


def build(export_dir, enums_path, output, moormap_path=None, overrides=None, landblocks_path=None,
          npcs_dir=None, did_positions=None, lore_dir=None, placed_entities=None, rewards_path=None):
    source = Source(export_dir)
    rewards = json.loads(Path(rewards_path).read_text(encoding='utf-8')) if rewards_path else {}
    overrides = overrides or {}
    hidden = set(overrides.get('hidden_ids', []))
    added = overrides.get('paths', {})
    enums = json.loads(Path(enums_path).read_text(encoding='utf-8'))
    quest_categories = enums['QuestCategory']
    deed_categories = enums['AccomplishmentUITab']
    # Which map a position is on comes from the game's own maps (parchment maps,
    # bounds, links). MoorMap only translates a game map into its map number, for
    # the "Show in MoorMap" button; without that number the button stays hidden.
    game = GameMaps(lore_dir or DEFAULT_LORE)
    moormap_of_image = moormap_index(moormap_path)

    def on_map(lat, lon, region):
        ident = game.attribute(lat, lon, region)
        if ident is None:
            return None
        found = {'gm': ident}
        # The button opens this map in MoorMap, or the next larger game map that
        # MoorMap knows; the position itself stays exactly as the game has it.
        for candidate in reversed(game.chain(ident)):
            number = moormap_of_image.get(game.maps[candidate]['image'])
            if number is not None:
                found['map'] = number
                break
        return found
    landblocks = source.load_landblocks(landblocks_path)
    from deed_locations import enemy_index, hunting_rule
    hunting = (enemy_index(placed_entities, did_positions, source.areas, landblocks, game.attribute)
               if placed_entities and did_positions and landblocks else {})

    if len(source.quests) < 1000 or len(source.deeds) < 100:
        raise ValueError('Implausibly small export; refusing to replace a working catalog')

    region_of = {zone: region for region, zones in REGIONS.items() for zone in zones}
    region_of_folded = {fold(zone): region for zone, region in region_of.items()}
    aliases = dict(ALIASES)
    for zone in region_of:
        aliases[zone] = zone
    area_parents = source.area_of_territory()
    area_parents_folded = defaultdict(set)
    for zone, names in area_parents.items():
        for name in names:
            area_parents_folded[fold(name)].add(zone)

    # Localized names of regions, zones and sub-areas, collected once.
    region_locales = defaultdict(dict)
    zone_locales = defaultdict(dict)
    area_locales = defaultdict(dict)
    for record in source.areas:
        props = record.get('properties') or {}
        texts = (props.get('Area_Name') or {}).get('texts') or {}
        english = texts.get('en')
        if not english:
            continue
        if props.get('Area_Territory') is None and props.get('Area_Region') is None:
            bucket = region_locales[english]
        elif props.get('Area_Territory') is None:
            bucket = zone_locales[english]
        else:
            bucket = area_locales[english]
        for locale in LOCALES:
            bucket[locale] = texts.get(locale) or english

    def zone_local(zone, locale):
        return ((zone_locales.get(zone) or {}).get(locale)
                or (region_locales.get(zone) or {}).get(locale) or zone)

    def region_local(region, locale):
        return ((REGION_NAMES.get(region) or {}).get(locale)
                or (region_locales.get(region) or {}).get(locale) or region)

    def area_local(area, category_loc):
        entry = area_locales.get(area) or {}
        if entry.get('en'):
            return entry
        if category_loc and ': ' in category_loc:
            return {locale: category_loc.split(': ', 1)[1] for locale in LOCALES}
        return {locale: area for locale in LOCALES}

    def place(category_en):
        """Category -> (zone, area, merged).

        An area named exactly like a known zone of the same region is that zone, not a
        sub-area. Without this the catalog showed some territories twice, e.g. under
        Mordor both "zone:Agarnaith" and "area:Mordor:Agarnaith" (from the categories
        "Agarnaith" and "Mordor: Agarnaith"). The test runs on the English keys only,
        so every language keeps the same tree; "merged" says the category lost its
        own level and must not reappear as a group below the zone.
        """
        if category_en in aliases:
            return aliases[category_en], None, False
        parents = area_parents.get(category_en) or area_parents_folded.get(fold(category_en))
        if parents and len(parents) == 1:
            zone = next(iter(parents))
            if zone in region_of:
                return zone, category_en, False
        if category_en and ': ' in category_en:
            prefix, suffix = category_en.split(': ', 1)
            if prefix in aliases:
                zone = aliases[prefix]
                if suffix in region_of and region_of[suffix] == region_of.get(zone):
                    return suffix, None, True
                return zone, suffix, False
        return None, None, False

    # Two facts that decide what a player can still finish. Both are language
    # independent, so they are worked out once from the English structure:
    #  * a session play is never written to the journal - no character can ever
    #    carry one as "finished" (all 87 in the export are absent from a played
    #    character's record);
    #  * two quests that each demand the other one "not started and not finished"
    #    rule each other out: whoever picked one cannot do the other.
    # The comparison operator from the DAT is 2 = NOT_EQUAL and 3 = EQUAL, with the
    # status mask 0x30000000 = completed and 0x10000000 = underway; that mapping was
    # checked against 1,886 prerequisites of quests this character has finished
    # (96 % of their targets are finished too).
    # Quest giver ("g"): the first NPC that bestows the quest, by name per language.
    # Names come from a separate export of those NPC records (npcs_dir); the game
    # marks grammar after a name ("Karlo Schwarzhain[mn]"), which is dropped.
    npc_names = {}
    if npcs_dir and (Path(npcs_dir) / 'raw.jsonl').is_file():
        for line in (Path(npcs_dir) / 'raw.jsonl').read_text(encoding='utf-8').splitlines():
            npc = json.loads(line)
            name = (npc.get('properties') or {}).get('Name')
            if isinstance(name, dict):
                npc_names[npc['id']] = {locale: re.sub(r'\[[^\]]*\]', '', text or '').strip()
                                        for locale, text in (name.get('texts') or {}).items()}
    giver_of = {}
    for entry in source.quests:
        for role in (entry.get('properties') or {}).get('Quest_BestowalRoles') or []:
            if isinstance(role, dict) and role.get('QuestDispenser_NPC'):
                npc = '%08X' % (int(role['QuestDispenser_NPC']) & 0xffffffff)
                if npc in npc_names:
                    giver_of[entry['id']] = npc
                    break

    session_ids = set()
    not_taken = defaultdict(set)
    for entry in source.quests:
        ident = entry['id']
        props = entry.get('properties') or {}
        if props.get('Quest_IsSessionQuest') == 1:
            session_ids.add(ident)
        for requirement in ((props.get('DefaultPermissionBlobStruct') or {})
                            .get('Usage_QuestRequirements') or []):
            if requirement.get('Usage_Operator') != 2:
                continue
            target = '%08X' % (int(requirement.get('Usage_QuestID', 0)) & 0xffffffff)
            if target != ident:
                not_taken[ident].add(target)
    # What a quest needs before it can be taken, as far as the data says it plainly:
    #   v  quests that must be completed (operator 3 = equal, status 0x30000000),
    #   vo of these, at least one (the game's OR list),
    #   vl minimum character level,
    #   vb 1 when anything else applies that we cannot check against a character
    #      (class, race, faction, craft, trait, effect, another quest under way…).
    COMPLETED = 0x30000000
    OTHER = ('Usage_RequiredFaction', 'Usage_RequiredClassList', 'Usage_RequiredRaces',
             'Usage_RequiredCraftProfession', 'Usage_RequiredTrait', 'Usage_RequiredCraftProficiency',
             'Usage_RequiredTrait_OrList', 'Usage_RequiredNeighborRelationship', 'Usage_RequiredEffect',
             'Usage_RequiredHobby', 'Usage_MinGloryRank', 'Usage_RequiredCraftProficiencyLocked',
             'Usage_WorldEvent_AllConditionList', 'Usage_WorldEvent_AnyConditionList')
    needs = {}
    for entry in source.quests:
        blob = (entry.get('properties') or {}).get('DefaultPermissionBlobStruct') or {}
        if not blob:
            continue
        need = {}
        must, other = [], any(blob.get(key) for key in OTHER)
        for requirement in blob.get('Usage_QuestRequirements') or []:
            target = '%08X' % (int(requirement.get('Usage_QuestID', 0)) & 0xffffffff)
            operator, status = requirement.get('Usage_Operator'), requirement.get('Usage_QuestStatus')
            if operator == 3 and status == COMPLETED:
                must.append(target)
            elif operator == 2:
                continue  # "not taken / not finished": handled as exclusions and by state
            else:
                other = True
        either = []
        for requirement in blob.get('Usage_QuestRequirements_OrList') or []:
            target = '%08X' % (int(requirement.get('Usage_QuestID', 0)) & 0xffffffff)
            if requirement.get('Usage_Operator') == 3 and requirement.get('Usage_QuestStatus') == COMPLETED:
                either.append(target)
        if (blob.get('Usage_QuestRequirements_OrList') or []) and not either:
            other = True
        if must:
            need['v'] = sorted(set(must))
        if either:
            need['vo'] = sorted(set(either))
        if isinstance(blob.get('Usage_MinLevel'), int) and blob['Usage_MinLevel'] > 1:
            need['vl'] = blob['Usage_MinLevel']
        if other:
            need['vb'] = 1
        if need:
            needs[entry['id']] = need

    exclusions = defaultdict(set)
    for ident, targets in not_taken.items():
        for target in targets:
            if ident in not_taken.get(target, ()):
                exclusions[ident].add(target)

    def section_for(category_en):
        if category_en.startswith('Mission'):
            return 'missions'
        if (category_en == 'Skirmish' or category_en.startswith(('Epic Battles', 'Dungeons'))
                or 'Instances' in category_en):
            return 'instances'
        if category_en.startswith('Craft'):
            return 'craft'
        if ('Festival' in category_en or 'Anniversary' in category_en
                or category_en in ('Farmers Faire', 'Hobnanigans')
                or category_en.startswith('Midsummer')):
            return 'festivals'
        return 'other'

    positions = defaultdict(list)
    # Where an NPC stands: every objective that names it as its target (talk to,
    # bring back to …) carries its position. An NPC seen at one place only gives
    # its quests a giver position ("gt"); one seen at places far apart gives none.
    npc_places = defaultdict(set)
    for row in source.locations:
        position = row.get('position') or {}
        lat, lon, region = position.get('latitude'), position.get('longitude'), position.get('region')
        if lat is None or lon is None or region is None:
            continue
        block = None
        if position.get('block_x') is not None and position.get('block_y') is not None:
            block = (str(region), str(position['block_x']), str(position['block_y']))
        positions[row['id']].append((row.get('objective_index'), lat, lon, region, block))
        if row.get('target_id'):
            npc_places[row['target_id']].add((region, round(lat, 2), round(lon, 2)))

    # Where every NPC, creature and object stands, read from the client's own geo
    # state (DidGeoExport.java). Preferred over the guess from other quests'
    # objectives, which only knows NPCs someone has to talk to.
    did_places = defaultdict(set)
    did_blocks = defaultdict(set)
    if did_positions and Path(did_positions).is_file():
        for line in Path(did_positions).read_text(encoding='utf-8').splitlines():
            row = json.loads(line)
            did_places[row['did']].add((row['region'], round(row['latitude'], 2), round(row['longitude'], 2)))
            if row.get('cell') == '00000000':
                did_blocks[row['did']].add((str(row['region']), str(row['block_x']), str(row['block_y'])))

    def one_spot(places):
        """Centre of places that are one spot (one region, within 0.3 map units), else None."""
        if not places or len({place[0] for place in places}) != 1:
            return None
        if max(p[1] for p in places) - min(p[1] for p in places) > 0.3 or \
                max(p[2] for p in places) - min(p[2] for p in places) > 0.3:
            return None
        return (next(iter(places))[0], round(sum(p[1] for p in places) / len(places), 2),
                round(sum(p[2] for p in places) / len(places), 2))

    # Objective events that name a placed thing: whom to talk to, what to kill or
    # use, which landmark to find.
    PLACED = ('QuestEvent_NPCTalk', 'QuestEvent_MonsterDID', 'QuestEvent_ItemDID',
              'QuestEvent_LandmarkDID', 'QuestEvent_EmoteTargetDID', 'QuestEvent_Detect')

    def placed_targets(objective):
        """Up to six distinct spots (rounded to 0.5 units) of the things an objective
        names, for objectives the target-location table leaves without a position."""
        events = []
        walk_events(objective.get('Quest_CompletionConditionArray') or [], events.append)
        spots = []
        for event in events:
            for key in PLACED:
                value = event.get(key)
                if not isinstance(value, int):
                    continue
                for region, lat, lon in sorted(did_places.get('%08X' % (value & 0xffffffff), ())):
                    rounded = (region, round(lat * 2) / 2, round(lon * 2) / 2)
                    if rounded not in [spot[3] for spot in spots]:
                        spots.append((lat, lon, region, rounded))
        return [(lat, lon, region) for lat, lon, region, _ in spots[:6]]

    # Territory of a target position, from the landblock index. Used only where the
    # category is not a zone, and only when every position agrees: a quest whose
    # objectives lie in several territories gets no invented zone.
    def territory_for(ident):
        found = set()
        # Where the quest giver stands counts as well (outdoors, one spot only).
        blocks = []
        npc = giver_of.get(ident)
        if npc and one_spot(did_places.get(npc)) is not None:
            blocks = list(did_blocks.get(npc, ()))
        # Where the quest is taken decides: a giver standing in one territory places
        # the quest there, even when its objectives spread over several.
        for block in blocks:
            area_id = landblocks.get(block)
            name = source.territory_name(area_id) if area_id is not None else None
            if name:
                found.add(name)
        if len(found) == 1:
            return found.pop()
        found = set()
        for _, lat, lon, region, block in positions.get(ident, []):
            area_id = landblocks.get(block) if block is not None else None
            if area_id is None:
                continue
            name = source.territory_name(area_id)
            if name:
                found.add(name)
        return found.pop() if len(found) == 1 else None

    def make_record(entry, kind, locale, stats, fallback):
        ident = entry['id']
        props = entry.get('properties') or {}
        if kind == 'quests':
            code = props.get('Quest_Category')
            categories = quest_categories
        else:
            code = props.get('Accomplishment_UITab')
            categories = deed_categories
        level = props.get('Quest_ChallengeLevel')
        labels = categories.get(str(code)) if code is not None else None
        category_en = (labels or {}).get('en')
        category_loc = (labels or {}).get(locale) or category_en

        if ident in hidden or (category_en in HIDDEN_CATEGORIES):
            stats[kind + '_hidden'] += 1
            return None
        # Developer placeholders: "DNT" (do not translate) and "HIDING CONTENT" in a
        # title. The game files them under normal areas, not as tests.
        if is_placeholder((entry.get('title') or {}).get('texts') or {}):
            stats[kind + '_hidden'] += 1
            stats[kind + '_hidden_placeholder'] += 1
            return None

        zone, area, merged = place(category_en)
        if zone is None:
            derived = territory_for(ident)
            if derived is not None and derived in region_of:
                zone, area, stats[kind + '_zone_from_position'] = derived, None, stats[kind + '_zone_from_position'] + 1
        if zone in HIDDEN_ZONES or (area and any(word in area for word in HIDDEN_AREA_WORDS)):
            stats[kind + '_hidden'] += 1
            return None

        path = []
        volume = STORY_VOLUME.match(category_en or '') if kind == 'quests' else None
        is_shadow = (category_en or '').startswith(SHADOW_PREFIX)
        is_story = kind == 'quests' and (
            volume is not None or category_en in STORY_EXTRA or is_shadow)
        if is_story:
            path.append({'k': 'section:more', 'n': '@more'})
            path.append({'k': 'section:story', 'n': '@story'})
            if volume is not None:
                path.append({'k': 'volume:' + volume.group(1), 'n': '@volume:' + volume.group(1)})
            elif is_shadow:
                path.append({'k': 'story:shadow', 'n': '@shadow'})
            if category_loc and category_loc != '@story':
                # The volume already heads the list section ("Band II"); the game's
                # category repeats it ("Epos - Band II, Buch 9: ...").
                label = re.sub(
                    r'^Epos\s*-\s*(?:Band|Volume|Reihe|Teil)?\s*' + re.escape(volume.group(1)) + r'\s*[,:]\s*',
                    '', category_loc) if volume is not None else category_loc
                path.append({'k': 'category:' + str(code), 'n': label})
        elif zone and zone in region_of:
            region = region_of[zone]
            path.append({'k': 'region:' + region, 'n': region_local(region, locale)})
            path.append({'k': 'zone:' + zone, 'n': zone_local(zone, locale)})
            if area:
                names = area_local(area, category_loc)
                path.append({'k': 'area:' + zone + ':' + area, 'n': names.get(locale) or names.get('en')})
            if category_loc and not merged and category_en != zone and category_en != area:
                path.append({'k': 'category:' + str(code), 'n': category_loc})
        else:
            section = section_for(category_en or '')
            if zone and zone not in region_of:
                stats['zones_without_region'] += 1
            path.append({'k': 'section:more', 'n': '@more'})
            path.append({'k': 'section:' + section, 'n': '@' + section})
            path.append({'k': 'category:' + str(code), 'n': category_loc or '@other'})
        if ident in added:
            path = added[ident]

        steps = []
        for objective in entry.get('objectives') or []:
            narrative, goals = [], []
            description = (objective.get('Quest_ObjectiveDescription') or {}).get('texts') or {}
            line = clean(description.get(locale) or description.get('en'))
            if line:
                if locale != 'en' and not description.get(locale):
                    fallback[kind] += 1
                narrative.append(line)
            seen_goals = set()

            # Conditions in their own order, numbered the way the game and LOTRO
            # Companion count them (objective index, then condition 0, 1, …), so a
            # character's running counter can be matched to its goal ("k"). Goals with
            # the same English label are shown once, decided on English so every
            # language keeps the same goals.
            conditions = []
            for group in objective.get('Quest_CompletionConditionArray') or []:
                conditions.extend(group if isinstance(group, list) else [group])

            for position, condition in enumerate(conditions):
                found = []
                walk_events(condition, lambda event: found.append(event)
                            if isinstance(event.get('QuestEvent_ProgressOverride'), dict) or
                            (kind == 'deeds' and isinstance(event.get('QuestEvent_BillboardProgressOverride'), dict))
                            else None)
                for event in found:
                    texts = (event.get('QuestEvent_ProgressOverride') or
                             event.get('QuestEvent_BillboardProgressOverride') or {}).get('texts') or {}
                    english = clean(texts.get('en'))
                    text = clean(texts.get(locale) or texts.get('en'))
                    if not text or (english or text) in seen_goals:
                        continue
                    seen_goals.add(english or text)
                    goal = {'t': counters(text), 'k': position}
                    number = event.get('QuestEvent_Number')
                    if isinstance(number, int) and number > 1:
                        goal['c'] = number
                    goals.append(goal)

            # Deeds can have real coordinates without any display text. Keep that
            # step only for direct defeat/landmark events, not hidden bestowal or
            # instance script triggers (their points may merely be entrances).
            direct = []
            walk_events(objective.get('Quest_CompletionConditionArray') or [],
                        lambda event: direct.append(event) if 'QuestEvent_ID' in event else None)
            if kind == 'deeds' and not narrative and not goals and direct and all(
                    e.get('QuestEvent_ID') == 22 and e.get('QuestEvent_MonsterDID')
                    and not e.get('QuestEvent_RoleConstraint') for e in direct):
                narrative.append({'de': 'In den Spieldaten verzeichnete Gegnerstandorte.',
                                  'en': 'Enemy locations recorded in the game data.',
                                  'fr': 'Positions des ennemis indiquées dans les données du jeu.'}[locale])
            if narrative or goals:
                steps.append({'i': str(objective.get('Quest_ObjectiveIndex', '')), 'n': narrative, 'g': goals})

        indexes = {step['i'] for step in steps}
        targets, seen = [], set()
        rows = list(positions.get(ident, []))
        covered = {str(row[0]) for row in rows}
        for objective in entry.get('objectives') or []:
            index = str(objective.get('Quest_ObjectiveIndex', ''))
            if index in covered or index not in indexes:
                continue
            for lat, lon, region in placed_targets(objective):
                rows.append((index, lat, lon, region, None))
                stats[kind + '_placed_targets'] += 1
        for objective_index, lat, lon, region, _ in rows:
            step_index = str(objective_index)
            if step_index not in indexes:
                continue
            # Two equally detailed maps no longer cancel each other (that dropped about
            # 3,300 entries): the smaller one wins, as for quest givers.
            chosen = on_map(lat, lon, region)
            if chosen is None:
                continue
            key = (chosen['gm'], round(lat, 5), round(lon, 5), step_index)
            if key in seen:
                continue
            seen.add(key)
            targets.append(dict(chosen, lat=round(lat, 5), lon=round(lon, 5), step=step_index))

        title = ((entry.get('title') or {}).get('texts') or {})
        name = clean(title.get(locale) or title.get('en'))
        if not name:
            name = ident
        elif locale != 'en' and not title.get(locale):
            fallback[kind] += 1
        description = ((entry.get('description') or {}).get('texts') or {})
        stats[kind] += 1
        stats[kind + '_with_targets'] += 1 if targets else 0
        stats[kind + '_targets'] += len(targets)
        # The core holds what tree, search, filters and counters need, plus the first
        # objective (the quest giver's map button). Description, steps and all
        # objectives live in a detail block and are imported when an entry is opened.
        text = clean(description.get(locale) or description.get('en'))
        core = {'id': ident, 'name': name,
                'l': level if level is not None else '', 'p': path}
        detail = {'d': text, 's': steps, 't': targets}
        granted = reward_entries(props, rewards, locale)
        if granted:
            stats[kind + '_with_rewards'] += 1
            stats[kind + '_rewards'] += len(granted)
            if kind == 'quests':
                detail['rw'] = granted
        if kind == 'deeds':
            # Deeds are small (1.4 MB for all three languages): they keep everything
            # in their own file, so the deed tab works without a second import. A
            # deed has no quest giver, so its own file's first objective places it.
            core['d'], core['s'], core['t'] = text, steps, targets;
            if granted:
                core['rw'] = granted
            hints = []
            for objective in entry.get('objectives') or []:
                index = str(objective.get('Quest_ObjectiveIndex', ''))
                if index not in indexes:
                    continue
                for point in hunting.get(hunting_rule(objective), []):
                    hint = dict(point, step=index)
                    for candidate in reversed(game.chain(point['gm'])):
                        number = moormap_of_image.get(game.maps[candidate]['image'])
                        if number is not None:
                            hint['map'] = number
                            break
                    hints.append(hint)
            if hints:
                core['h'] = hints
                stats['deeds_with_hunting'] += 1
                stats['deeds_hunting_points'] += len(hints)
            detail = {};
        else:
            if len(steps) > 0:
                core['sc'] = len(steps)
        # ls: the level follows the character (the game takes it from a property),
        # so the stored level is only a floor, often 1.
        if props.get('Quest_ChallengeLevelOverrideProperty'):
            core['ls'] = 1
            stats[kind + '_scaling'] += 1
        npc = giver_of.get(ident) if kind == 'quests' else None
        # Small differences are the same spot (an NPC pacing): within 0.3 map units in
        # one region the centre counts; anything wider stays without a giver dot.
        spot = (one_spot(did_places.get(npc)) or one_spot(npc_places.get(npc))) if npc else None
        if spot is not None:
            region, lat, lon = spot
            chosen = on_map(lat, lon, region)
            if chosen is not None:
                core['gt'] = dict(chosen, lat=lat, lon=lon)
                stats['quests_with_giver_position'] += 1
        # Plain facts from the record, each only when the game sets it:
        #   nq next quest, rp repeatable (-1 any number of times, else up to n),
        #   dy resets daily, tl time limit in seconds, gr 2 = fellowship / 1 = small
        #   fellowship recommended, ix instance, lp LOTRO points.
        nxt = props.get('Quest_NextQuest')
        if isinstance(nxt, int) and nxt:
            core['nq'] = '%08X' % (nxt & 0xffffffff)
        times = props.get('Quest_MaxTimesCompletable')
        if isinstance(times, int) and (times == -1 or times > 1):
            core['rp'] = times
        if props.get('Quest_IsDailyGlobalReset') == 1:
            core['dy'] = 1
        limit = props.get('Quest_TimeLimit')
        if isinstance(limit, (int, float)) and limit > 0:
            core['tl'] = int(limit)
        if props.get('Quest_IsFellowshipRecommended') == 1:
            core['gr'] = 2
        elif props.get('Quest_IsSmallFellowshipRecommended') == 1:
            core['gr'] = 1
        if props.get('Quest_IsInstanceQuest') == 1:
            core['ix'] = 1
        # LOTRO points come as a tier. Checked against 2,606 deeds (LOTRO Companion's
        # lore, used only to verify): 2 = 5, 3 = 10, 4 = 15, 5 = 20, 6 = 50, no
        # exception. Other tiers are not mapped.
        points = {2: 5, 3: 10, 4: 15, 5: 20, 6: 50}.get(props.get('Quest_TurbinePointTier'))
        if points:
            core['lp'] = points
        # rf: the faction this gives reputation with and the game's reward tier
        # (1-6, a relative size; the points per tier are not in the data).
        reward = props.get('Quest_PositiveFaction')
        if isinstance(reward, dict) and reward.get('Quest_FactionDID'):
            core['rf'] = ['%08X' % (int(reward['Quest_FactionDID']) & 0xffffffff),
                            int(reward.get('Quest_RepTier') or 0)]
            stats[kind + '_with_reputation'] += 1
        return core, detail

    manifest = {'schema': SCRIPT_VERSION, 'sources': {}, 'locales': {}, 'source_manifest': {}}
    for name in ('quests.json', 'deeds.json', 'areas.json', 'locations.json'):
        manifest['sources'][name] = hashlib.sha256((Path(export_dir) / name).read_bytes()).hexdigest()
    manifest['sources']['enums/enum-names.json'] = hashlib.sha256(Path(enums_path).read_bytes()).hexdigest()
    lore = Path(lore_dir or DEFAULT_LORE)
    for name in ('parchmentMaps.xml', 'maps/maps/maps.xml', 'maps/links.xml'):
        manifest['sources'][name] = hashlib.sha256((lore / name).read_bytes()).hexdigest()
    if moormap_path is not None:
        # Map numbers for the "Show in MoorMap" button only.
        manifest['sources']['MoorMap/Defaults.lua (map numbers only)'] = \
            hashlib.sha256(Path(moormap_path).read_bytes()).hexdigest()
    if landblocks_path is not None:
        manifest['sources']['landblocks.xml'] = hashlib.sha256(Path(landblocks_path).read_bytes()).hexdigest()
    manifest['source_manifest'] = {'created_utc': source.manifest.get('created_utc'),
                                   'backend': source.manifest.get('backend'),
                                   'languages': source.manifest.get('languages')}

    output.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix='.mql-build-', dir=str(output.parent)))
    try:
        for locale in LOCALES:
            stats, fallback = Counter(), Counter()
            for kind, source_list in (('quests', source.quests), ('deeds', source.deeds)):
                records, details = [], {}
                for entry in source_list:
                    built = make_record(entry, kind, locale, stats, fallback)
                    if built is not None:
                        core, detail = built
                        records.append(core)
                        if kind == 'quests':
                            details[core['id']] = detail
                # pq: quests that lead here (their "next quest" is this one).
                visible_ids = {r['id'] for r in records}
                previous = defaultdict(list)
                for record in records:
                    if record.get('nq') in visible_ids:
                        previous[record['nq']].append(record['id'])
                    elif 'nq' in record:
                        del record['nq']
                for record in records:
                    if record['id'] in previous:
                        record['pq'] = sorted(previous[record['id']])
                if kind == 'quests':
                    # These two fields only name entries the catalog still shows:
                    # a pointer at a hidden test entry would dangle.
                    visible = {r['id'] for r in records}
                    for record in records:
                        npc = giver_of.get(record['id'])
                        if npc:
                            names = npc_names[npc]
                            giver = names.get(locale) or names.get('en')
                            if giver:
                                record['g'] = giver
                                stats['quests_with_giver'] += 1
                        for key, value in needs.get(record['id'], {}).items():
                            record[key] = value
                        if record['id'] in needs:
                            stats['quests_with_requirements'] += 1
                        if record['id'] in session_ids:
                            record['x'] = 1
                            stats['quests_session'] += 1
                        mates = sorted(exclusions.get(record['id'], set()) & visible)
                        if mates:
                            record['ex'] = mates
                            stats['quests_mutually_exclusive'] += 1
                if kind == 'quests':
                    # Detail blocks by id range: the same blocks in every language,
                    # so a character's entries load the same files after a swap.
                    order = sorted(r['id'] for r in records)
                    block = {ident: position // DETAIL_BLOCK + 1 for position, ident in enumerate(order)}
                    for core in records:
                        core['blk'] = block[core['id']]
                    grouped = defaultdict(dict)
                    for ident, detail in details.items():
                        grouped[block[ident]][ident] = detail
                    for number in sorted(grouped):
                        entries = grouped[number]
                        parts, ids = [], sorted(entries)
                        for start in range(0, len(ids), 500):
                            parts.append('(function(t)\n' + '\n'.join(
                                't[%s]=%s;' % (lua(ident), lua(entries[ident]))
                                for ident in ids[start:start + 500]) + '\nend)(MagicQuestLog.Data.%s);'
                                % ('questDetails_%s_%d' % (locale, number)))
                        (staging / ('QuestDetails_%s_%d.lua' % (locale, number))).write_text(
                            MARKER + 'MagicQuestLog = MagicQuestLog or {};\nMagicQuestLog.Data = MagicQuestLog.Data or {};\n'
                            'MagicQuestLog.Data.%s = {};\n' % ('questDetails_%s_%d' % (locale, number))
                            + '\n'.join(parts) + '\n', encoding='utf-8')
                    stats['quests_detail_blocks'] = len(grouped)
                # Lua 5.1 allows about 262,000 constants per function; one table
                # constructor for the whole catalog runs over it. Each block of
                # records gets its own function and with it its own constant table.
                name = '%s_%s' % (kind, locale)
                blocks = []
                for start in range(0, len(records), 1000):
                    blocks.append('(function(t)\n' + '\n'.join(
                        't[%d]=%s;' % (start + offset + 1, lua(r))
                        for offset, r in enumerate(records[start:start + 1000])) + '\nend)(MagicQuestLog.Data.%s);' % name)
                (staging / ('%s_%s.lua' % (kind.capitalize(), locale))).write_text(
                    MARKER + 'MagicQuestLog = MagicQuestLog or {};\nMagicQuestLog.Data = MagicQuestLog.Data or {};\n'
                    'MagicQuestLog.Data.%s = {};\n' % name
                    + '\n'.join(blocks) + '\n', encoding='utf-8')
            manifest['locales'][locale] = {
                'counts': dict(stats),
                'english_fallback_texts': dict(fallback),
            }
        (staging / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
        # A rebuild may need fewer detail blocks; stale ones would stay importable.
        expected = {path.name for path in staging.glob('QuestDetails_*.lua')}
        for stale in output.glob('QuestDetails_*.lua'):
            if stale.name in expected:
                continue
            if stale.read_text(encoding='utf-8').startswith(MARKER):
                stale.unlink()
        for source_file in sorted(staging.rglob('*')):
            if not source_file.is_file():
                continue
            target = output / source_file.relative_to(staging)
            if source_file.suffix == '.lua' and target.is_file():
                if not target.read_text(encoding='utf-8').startswith(MARKER):
                    raise ValueError('Refusing to replace a file Magic Quest Log did not generate: ' + str(target))
            target.parent.mkdir(parents=True, exist_ok=True)
            temp = target.with_name(target.name + '.new')
            temp.write_bytes(source_file.read_bytes())
            temp.replace(target)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return manifest


def main():
    parser = argparse.ArgumentParser(description='Build Magic Quest Log catalogs from our own DAT export.')
    parser.add_argument('--export', type=Path, required=True, help='Export directory (quests.json, ...)')
    parser.add_argument('--enums', type=Path, required=True, help='enum-names.json from the enum export')
    parser.add_argument('--moormap', type=Path, default=None,
                        help="MoorMap Defaults.lua: only its map numbers, for the plugin's MoorMap button")
    parser.add_argument('--lore', type=Path, default=None,
                        help="LOTRO Companion's lore directory (parchmentMaps.xml, maps/): the game's maps")
    parser.add_argument('--landblocks', type=Path, default=None,
                        help='landblocks.xml: ties target positions to a territory')
    parser.add_argument('--npcs', type=Path, default=None,
                        help='export of the quest-giving NPCs (raw.jsonl): adds the giver per quest')
    parser.add_argument('--did-positions', type=Path, default=None,
                        help='positions.jsonl from DidGeoExport.java: where NPCs, creatures and objects stand')
