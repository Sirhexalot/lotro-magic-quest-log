def clean(text):
    """Game text: literal \\q is a quote, literal \\n is a line break."""
    if text is None:
        return ''
    return text.replace('\\q', '"').replace('\\n', '\n').strip()


def fold(text):
    """Accent-free lowercase form for name comparisons between languages."""
    text = (text or '').lower()
    for source, target in (('á','a'),('à','a'),('â','a'),('ä','a'),('ã','a'),('å','a'),
                           ('é','e'),('è','e'),('ê','e'),('ë','e'),
                           ('í','i'),('ì','i'),('î','i'),('ï','i'),
                           ('ó','o'),('ò','o'),('ô','o'),('ö','o'),('õ','o'),
                           ('ú','u'),('ù','u'),('û','u'),('ü','u'),
                           ('ç','c'),('ñ','n'),('ß','ss')):
        text = text.replace(source, target)
    return text


def lua(value):
    if value is None:
        return 'nil'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False).replace('\\/', '/')
    if isinstance(value, (list, tuple)):
        return '{' + ','.join(lua(v) for v in value) + '}'
    if isinstance(value, dict):
        return '{' + ','.join('[' + lua(str(k)) + ']=' + lua(v) for k, v in value.items()) + '}'
    raise TypeError(type(value))


def moor_map_table(path):
    """MoorMap's own map geometry. The export carries no texture id, so a position is
    attributed to the most specific map whose region and bounds contain it. Two maps
    of the same tier matching means ambiguous, and the position is dropped."""
    maps = []
    if path is None:
        return maps
    for match in re.finditer(r'tmpMapInfo\[(\d+)\]\s*=\s*\{([^}\n]+)', path.read_text()):
        fields = match.group(2).split(',')
        try:
            entry = dict(map=int(fields[0]), kind=int(fields[10]), region=int(fields[11]),
                         north=float(fields[12]), west=float(fields[13]),
                         south=float(fields[14]), east=float(fields[15]), tier=int(fields[16]))
        except (ValueError, IndexError):
            continue
        if entry['kind'] == 1:
            maps.append(entry)
    return maps


def attribute(maps, lat, lon, region):
    hits = [m for m in maps
            if m['south'] <= lat <= m['north'] and m['west'] <= lon <= m['east']
            and m['region'] == region]
    if not hits:
        return None
    best = max(m['tier'] for m in hits)
    top = [m for m in hits if m['tier'] == best]
    return top[0] if len(top) == 1 else None


def counters(text):
    """The DAT renderer strips the ${...} wrapper, so counting marks arrive as
    "NUMBER/TOTAL". Restore what the plugin's text resolver understands."""
    if 'NUMBER' not in text and 'TOTAL' not in text:
        return text
    return re.sub(r'\(\s*NUMBER\s*/\s*TOTAL\s*([^)]*)\)',
                  lambda m: '(${NUMBER}/${TOTAL}' + m.group(1) + ')', text)


def walk_events(container, visit):
    stack = [container]
    while stack:
        current = stack.pop()
        if isinstance(current, list):
            stack.extend(current)
        elif isinstance(current, dict):
            visit(current)
            for value in current.values():
                if isinstance(value, (list, dict)):
                    stack.append(value)


class Source:
    def __init__(self, directory):
        self.directory = directory
        self.manifest = json.loads((directory / 'manifest.json').read_text(encoding='utf-8'))
        self.quests = json.loads((directory / 'quests.json').read_text(encoding='utf-8'))
        self.deeds = json.loads((directory / 'deeds.json').read_text(encoding='utf-8'))
        self.areas = json.loads((directory / 'areas.json').read_text(encoding='utf-8'))
        self.area_by_id = {r['id']: r for r in self.areas}
        self.locations = json.loads((directory / 'locations.json').read_text(encoding='utf-8'))

    def load_landblocks(self, path):
        """Landblock -> area id, so a target position can be tied to a territory.

        Only used as a fallback for entries whose category is not a zone. The table
        is a plain index; nothing about a quest is invented from it.
        """
        if path is None:
            return {}
        import xml.etree.ElementTree as ET
        index = {}
        for block in ET.parse(path).getroot():
            index[(block.get('region'), block.get('blockX'), block.get('blockY'))] = block.get('areaId')
        return index

    def territory_name(self, area_id):
        record = self.area_by_id.get('%08X' % (int(area_id) & 0xffffffff))
        if record is None:
            return None
        props = record.get('properties') or {}
        parent = props.get('Area_Territory')
        if parent is not None:
            record = self.area_by_id.get('%08X' % (parent & 0xffffffff))
            if record is None:
                return None
            props = record.get('properties') or {}
        return (props.get('Area_Name') or {}).get('texts', {}).get('en')

    def area_of_territory(self):
        """Sub-area name -> set of territory names it belongs to.

        Keyed by the area's own name, because a quest category carries a name, not an
        id. A name that occurs under more than one territory stays ambiguous and is
        never guessed into a zone.
        """
        territory_by_id = {}
        for record in self.areas:
            props = record.get('properties') or {}
            name = (props.get('Area_Name') or {}).get('texts', {}).get('en')
            if name and props.get('Area_Territory') is None:
                territory_by_id['%08X' % (int(record['id'], 16))] = name
        parents = defaultdict(set)
        for record in self.areas:
            props = record.get('properties') or {}
            parent = props.get('Area_Territory')
            if parent is None:
                continue
            name = (props.get('Area_Name') or {}).get('texts', {}).get('en')
            territory = territory_by_id.get('%08X' % (parent & 0xffffffff))
            if name and territory:
                parents[name].add(territory)
        return parents


def build(export_dir, enums_path, output, moormap_path=None, overrides=None, landblocks_path=None):
    source = Source(export_dir)
    overrides = overrides or {}
    hidden = set(overrides.get('hidden_ids', []))
    added = overrides.get('paths', {})
    enums = json.loads(Path(enums_path).read_text(encoding='utf-8'))
    quest_categories = enums['QuestCategory']
    deed_categories = enums['AccomplishmentUITab']
    maps = moor_map_table(moormap_path)
    landblocks = source.load_landblocks(landblocks_path)

    if len(source.quests) < 1000 or len(source.deeds) < 100:
        raise ValueError('Implausibly small export; refusing to replace a working catalog')

    region_of = {zone: region for region, zones in REGIONS.items() for zone in zones}
    region_of_folded = {fold(zone): region for zone, region in region_of.items()}
    aliases = dict(ALIASES)
    for zone in region_of:
        aliases[zone] = zone
    area_parents = source.area_of_territory()
    area_parents_folded = defaultdict(set)
    for zone, names in area_parents.items():
        for name in names:
            area_parents_folded[fold(name)].add(zone)

    # Localized names of regions, zones and sub-areas, collected once.
    region_locales = defaultdict(dict)
    zone_locales = defaultdict(dict)
    area_locales = defaultdict(dict)
    for record in source.areas:
        props = record.get('properties') or {}
        texts = (props.get('Area_Name') or {}).get('texts') or {}
        english = texts.get('en')
        if not english:
            continue
        if props.get('Area_Territory') is None and props.get('Area_Region') is None:
            bucket = region_locales[english]
        elif props.get('Area_Territory') is None:
            bucket = zone_locales[english]
        else:
            bucket = area_locales[english]
        for locale in LOCALES:
            bucket[locale] = texts.get(locale) or english

    def zone_local(zone, locale):
        return ((zone_locales.get(zone) or {}).get(locale)
                or (region_locales.get(zone) or {}).get(locale) or zone)

    def region_local(region, locale):
        return ((REGION_NAMES.get(region) or {}).get(locale)
                or (region_locales.get(region) or {}).get(locale) or region)

    def area_local(area, category_loc):
        entry = area_locales.get(area) or {}
        if entry.get('en'):
            return entry
        if category_loc and ': ' in category_loc:
            return {locale: category_loc.split(': ', 1)[1] for locale in LOCALES}
        return {locale: area for locale in LOCALES}

    def place(category_en):
        if category_en in aliases:
            return aliases[category_en], None
        parents = area_parents.get(category_en) or area_parents_folded.get(fold(category_en))
        if parents and len(parents) == 1:
            zone = next(iter(parents))
            if zone in region_of:
                return zone, category_en
        if category_en and ': ' in category_en:
            prefix, suffix = category_en.split(': ', 1)
            if prefix in aliases:
                return aliases[prefix], suffix
        return None, None

    def section_for(category_en):
        if category_en.startswith('Mission'):
            return 'missions'
        if (category_en == 'Skirmish' or category_en.startswith(('Epic Battles', 'Dungeons'))
                or 'Instances' in category_en):
            return 'instances'
        if category_en.startswith('Craft'):
            return 'craft'
        if ('Festival' in category_en or 'Anniversary' in category_en
                or category_en in ('Farmers Faire', 'Hobnanigans')
                or category_en.startswith('Midsummer')):
            return 'festivals'
        return 'other'

    positions = defaultdict(list)
    for row in source.locations:
        position = row.get('position') or {}
        lat, lon, region = position.get('latitude'), position.get('longitude'), position.get('region')
        if lat is None or lon is None or region is None:
            continue
        block = None
        if position.get('block_x') is not None and position.get('block_y') is not None:
            block = (str(region), str(position['block_x']), str(position['block_y']))
        positions[row['id']].append((row.get('objective_index'), lat, lon, region, block))

    # Territory of a target position, from the landblock index. Used only where the
    # category is not a zone, and only when every position agrees: a quest whose
    # objectives lie in several territories gets no invented zone.
    def territory_for(ident):
        found = set()
        for _, lat, lon, region, block in positions.get(ident, []):
            area_id = landblocks.get(block) if block is not None else None
            if area_id is None:
                continue
            name = source.territory_name(area_id)
            if name:
                found.add(name)
        return found.pop() if len(found) == 1 else None

    def make_record(entry, kind, locale, stats, fallback):
        ident = entry['id']
        props = entry.get('properties') or {}
        if kind == 'quests':
            code = props.get('Quest_Category')
            categories = quest_categories
        else:
            code = props.get('Accomplishment_UITab')
            categories = deed_categories
        level = props.get('Quest_ChallengeLevel')
        labels = categories.get(str(code)) if code is not None else None
        category_en = (labels or {}).get('en')
        category_loc = (labels or {}).get(locale) or category_en

        if ident in hidden or (category_en in HIDDEN_CATEGORIES):
            stats[kind + '_hidden'] += 1
            return None

        zone, area = place(category_en)
        if zone is None:
            derived = territory_for(ident)
            if derived is not None and derived in region_of:
                zone, area, stats[kind + '_zone_from_position'] = derived, None, stats[kind + '_zone_from_position'] + 1
        if zone in HIDDEN_ZONES or (area and any(word in area for word in HIDDEN_AREA_WORDS)):
            stats[kind + '_hidden'] += 1
            return None

        path = []
        volume = STORY_VOLUME.match(category_en or '') if kind == 'quests' else None
        is_shadow = (category_en or '').startswith(SHADOW_PREFIX)
        is_story = kind == 'quests' and (
            volume is not None or category_en in STORY_EXTRA or is_shadow)
        if is_story:
            path.append({'k': 'section:story', 'n': '@story'})
            if volume is not None:
                path.append({'k': 'volume:' + volume.group(1), 'n': '@volume:' + volume.group(1)})
            elif is_shadow:
                path.append({'k': 'story:shadow', 'n': '@shadow'})
            if category_loc and category_loc != '@story':
                path.append({'k': 'category:' + str(code), 'n': category_loc})
        elif zone and zone in region_of:
            region = region_of[zone]
            path.append({'k': 'region:' + region, 'n': region_local(region, locale)})
            path.append({'k': 'zone:' + zone, 'n': zone_local(zone, locale)})
            if area:
                names = area_local(area, category_loc)
                path.append({'k': 'area:' + zone + ':' + area, 'n': names.get(locale) or names.get('en')})
            if category_loc and category_en != zone and category_en != area:
                path.append({'k': 'category:' + str(code), 'n': category_loc})
        else:
            section = section_for(category_en or '')
            if zone and zone not in region_of:
                stats['zones_without_region'] += 1
            path.append({'k': 'section:' + section, 'n': '@' + section})
            path.append({'k': 'category:' + str(code), 'n': category_loc or '@other'})
        if ident in added:
            path = added[ident]

        steps = []
        for objective in entry.get('objectives') or []:
            narrative, goals = [], []
            description = (objective.get('Quest_ObjectiveDescription') or {}).get('texts') or {}
            line = clean(description.get(locale) or description.get('en'))
            if line:
                if locale != 'en' and not description.get(locale):
                    fallback[kind] += 1
                narrative.append(line)
            seen_goals = set()

            def collect(event):
                override = event.get('QuestEvent_ProgressOverride')
                if not isinstance(override, dict):
                    return
                texts = override.get('texts') or {}
                text = clean(texts.get(locale) or texts.get('en'))
                if not text or text in seen_goals:
                    return
                seen_goals.add(text)
                goal = {'t': counters(text)}
                number = event.get('QuestEvent_Number')
                if isinstance(number, int) and number > 1:
                    goal['c'] = number
                goals.append(goal)

            walk_events(objective.get('Quest_CompletionConditionArray') or [], collect)
            if narrative or goals:
                steps.append({'i': str(objective.get('Quest_ObjectiveIndex', '')), 'n': narrative, 'g': goals})

        indexes = {step['i'] for step in steps}
        targets, seen = [], set()
        for objective_index, lat, lon, region, _ in positions.get(ident, []):
            step_index = str(objective_index)
            if step_index not in indexes:
                continue
            chosen = attribute(maps, lat, lon, region)
            if chosen is None:
                continue
            key = (chosen['map'], round(lat, 5), round(lon, 5), step_index)
            if key in seen:
                continue
            seen.add(key)
            targets.append({'map': chosen['map'], 'lat': round(lat, 5), 'lon': round(lon, 5), 'step': step_index})

        title = ((entry.get('title') or {}).get('texts') or {})
        name = clean(title.get(locale) or title.get('en'))
        if not name:
            name = ident
        elif locale != 'en' and not title.get(locale):
            fallback[kind] += 1
        description = ((entry.get('description') or {}).get('texts') or {})
        stats[kind] += 1
        stats[kind + '_with_targets'] += 1 if targets else 0
        stats[kind + '_targets'] += len(targets)
        return {'id': ident, 'name': name,
                'd': clean(description.get(locale) or description.get('en')),
                'l': level if level is not None else '',
                'p': path, 's': steps, 't': targets}

    manifest = {'schema': SCRIPT_VERSION, 'sources': {}, 'locales': {}, 'source_manifest': {}}
    for name in ('quests.json', 'deeds.json', 'areas.json', 'locations.json'):
        manifest['sources'][name] = hashlib.sha256((Path(export_dir) / name).read_bytes()).hexdigest()
    manifest['sources']['enums/enum-names.json'] = hashlib.sha256(Path(enums_path).read_bytes()).hexdigest()
    if moormap_path is not None:
        manifest['sources']['MoorMap/Defaults.lua'] = hashlib.sha256(Path(moormap_path).read_bytes()).hexdigest()
    if landblocks_path is not None:
        manifest['sources']['landblocks.xml'] = hashlib.sha256(Path(landblocks_path).read_bytes()).hexdigest()
    manifest['source_manifest'] = {'created_utc': source.manifest.get('created_utc'),
                                   'backend': source.manifest.get('backend'),
                                   'languages': source.manifest.get('languages')}

    output.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix='.mql-build-', dir=str(output.parent)))
    try:
        for locale in LOCALES:
            stats, fallback = Counter(), Counter()
            for kind, source_list in (('quests', source.quests), ('deeds', source.deeds)):
                records = []
                for entry in source_list:
                    built = make_record(entry, kind, locale, stats, fallback)
                    if built is not None:
                        records.append(built)
                (staging / ('%s_%s.lua' % (kind.capitalize(), locale))).write_text(
                    MARKER + 'MagicQuestLog = MagicQuestLog or {};\nMagicQuestLog.Data = MagicQuestLog.Data or {};\n'
                    'MagicQuestLog.Data.%s_%s = {\n' % (kind, locale)
                    + ',\n'.join(lua(r) for r in records) + '\n};\n', encoding='utf-8')
            manifest['locales'][locale] = {
                'counts': dict(stats),
                'english_fallback_texts': dict(fallback),
            }
        (staging / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
        for source_file in sorted(staging.rglob('*')):
            if not source_file.is_file():
                continue
            target = output / source_file.relative_to(staging)
            if source_file.suffix == '.lua' and target.is_file():
                if not target.read_text(encoding='utf-8').startswith(MARKER):
                    raise ValueError('Refusing to replace a file Magic Quest Log did not generate: ' + str(target))
            target.parent.mkdir(parents=True, exist_ok=True)
            temp = target.with_name(target.name + '.new')
            temp.write_bytes(source_file.read_bytes())
            temp.replace(target)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return manifest


def main():
    parser = argparse.ArgumentParser(description='Build Magic Quest Log catalogs from our own DAT export.')
    parser.add_argument('--export', type=Path, required=True, help='Export directory (quests.json, ...)')
    parser.add_argument('--enums', type=Path, required=True, help='enum-names.json from the enum export')
    parser.add_argument('--moormap', type=Path, default=None, help='MoorMap Defaults.lua')
    parser.add_argument('--landblocks', type=Path, default=None,
                        help='landblocks.xml: ties target positions to a territory')
    parser.add_argument('--output', type=Path, default=ROOT / 'plugin/MagicQuestLog/Data')
    parser.add_argument('--overrides', type=Path, default=ROOT / 'tools/overrides.json')
    options = parser.parse_args()
    data = json.loads(options.overrides.read_text(encoding='utf-8')) if options.overrides.is_file() else {}
    report = build(options.export, options.enums, options.output, options.moormap, data,
                   options.landblocks)
    print(json.dumps({k: v['counts'] for k, v in report['locales'].items()}, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
